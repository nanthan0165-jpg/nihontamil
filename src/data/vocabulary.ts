function numberToHiraAndPron(n: number): { hira: string, pron: string, kanji: string } {
  if (n === 100) return { hira: "ひゃく", pron: "ஹ்யாகு", kanji: "百" };
  if (n <= 10) return { hira: numHiraBase[n], pron: numPronBase[n], kanji: numKanjiBase[n] };
  if (n < 20) {
    const rem = n % 10;
    return { hira: "じゅう" + numHiraBase[rem], pron: "ஜூ" + numPronBase[rem], kanji: "十" + numKanjiBase[rem] };
  }
  const div = Math.floor(n / 10);
  const rem = n % 10;
  const prefixHira = div === 1 ? "じゅう" : numHiraBase[div] + "じゅう";
  const prefixPron = div === 1 ? "ஜூ" : numPronBase[div] + "ஜூ";
  const prefixKanji = div === 1 ? "十" : numKanjiBase[div] + "十";
  return {
    hira: prefixHira + numHiraBase[rem],
    pron: prefixPron + numPronBase[rem],
    kanji: prefixKanji + numKanjiBase[rem]
  };
}

