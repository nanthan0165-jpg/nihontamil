// Helper to expand base numbers programmatically up to 100
function generateNumbers(): Vocabulary[] {
  const list: Vocabulary[] = [];
  const numMap: { [key: number]: [string, string, string, string] } = {
    1: ["一", "いち", "இச்சி", "ஒன்று"],
    2: ["二", "に", "நி", "இரண்டு"],
    3: ["三", "さん", "ஸான்", "மூன்று"],
    4: ["四", "よん", "யோன்", "நான்கு"],
    5: ["五", "ご", "கோ", "ஐந்து"],
    6: ["六", "ろく", "ரோக்கு", "ஆறு"],
    7: ["七", "なな", "நனா", "ஏழு"],
    8: ["八", "はち", "ஹச்சி", "எட்டு"],
    9: ["九", "きゅう", "க்யூ", "ஒன்பது"],
    10: ["十", "じゅう", "ஜூ", "பத்து"],
    100: ["百", "ひゃく", "ஹ்யாகு", "நூறு"]
  };

  // 1 to 100 loop to generate 100 vocabulary items
  for (let i = 1; i <= 100; i++) {
    let kanji = "";
    let hira = "";
    let tamilPron = "";
    let tamilMean = "";

    if (numMap[i]) {
      [kanji, hira, tamilPron, tamilMean] = numMap[i];
    } else if (i < 20) {
      const rem = i % 10;
      kanji = "十" + numMap[rem][0];
      hira = "じゅう" + numMap[rem][1];
      tamilPron = "ஜூ-" + numMap[rem][2];
      tamilMean = "பதினொன்று,பன்னிரண்டு,பதின்மூன்று,பதினான்கு,பதினைந்து,பதினாறு,பதினேழு,பதினெட்டு,பத்தொன்பது"[i - 11];
      // simplified descriptive tamil mean
      const meanList = ["பதினொன்று", "பன்னிரண்டு", "பதின்மூன்று", "பதினான்கு", "பதினைந்து", "பதினாறு", "பதினேழு", "பதினெட்டு", "பத்தொன்பது"];
      tamilMean = meanList[i - 11];
    } else {
      const div = Math.floor(i / 10);
      const rem = i % 10;
      const prefixKanji = div === 1 ? "十" : numMap[div][0] + "十";
      const prefixHira = div === 1 ? "じゅう" : numMap[div][1] + "じゅう";
      const prefixPron = div === 1 ? "ஜூ-" : numMap[div][2] + "-ஜூ-";
      
      kanji = prefixKanji + (rem > 0 ? numMap[rem][0] : "");
      hira = prefixHira + (rem > 0 ? numMap[rem][1] : "");
      tamilPron = prefixPron + (rem > 0 ? numMap[rem][2] : "");
      
      const tensMean = ["", "பத்து", "இருபது", "முப்பது", "நாற்பது", "ஐம்பது", "அறுபது", "எழுபது", "எண்பது", "தொண்ணூறு"][div];
      const onesMean = ["", " ஒன்று", " இரண்டு", " மூன்று", " நான்கு", " ஐந்து", " ஆறு", " ஏழு", " எட்டு", " ஒன்பது"][rem];
      tamilMean = tensMean + onesMean;
    }

    list.push({
      id: `num-${i}`,
      japanese: kanji,
      hiragana: hira,
      tamilPronunciation: tamilPron,
      tamilMeaning: `எண் ${i} (${tamilMean})`,
      exampleSentence: `リンゴが ${kanji}つあります。 (ஆப்பிள் ${i} உள்ளது.)`,
      partOfSpeech: "எண்",
      level: "N5"
    });
  }
  return list;
}

